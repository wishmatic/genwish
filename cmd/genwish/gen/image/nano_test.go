func TestGenerateImageWritesInlineImages(t *testing.T) {
	encoded := base64.StdEncoding.EncodeToString(testutil.PNG)
	body := fmt.Sprintf(`{"data":[{"b64_json":%q},{"b64_json":%q}],"cost":0.02}`, encoded, encoded)

	server, requests := testutil.CaptureServer(t, http.StatusOK, body)
	dir := t.TempDir()

	out, _, err := runNano(
		t,
		cli.Deps{Nano: testutil.NewNanoClient(t, server.URL)},
		"a cat",
		"--model",
		"image-model",
		"--n",
		"2",
		"--size",
		"1024x1024",
		"--seed",
		"42",
		"--strength",
		"0.5",
		"--guidance-scale",
		"7.5",
		"--num-inference-steps",
		"20",
		"--format",
		"png",
		"--out",
		dir,
	)
	if err != nil {
		t.Fatalf("Execute() error: %v", err)
	}

	request := testutil.NextRequest(t, requests)
	if request.Path != "/api/v1/images/generations" {
		t.Errorf("path = %s, want /api/v1/images/generations", request.Path)
	}
	if auth := request.Header.Get("Authorization"); auth != "Bearer test-key" {
		t.Errorf("Authorization = %q, want Bearer test-key", auth)
	}

	bodyJSON := request.JSONBody(t)
	checks := map[string]any{
		"prompt":              "a cat",
		"model":               "image-model",
		"n":                   float64(2),
		"size":                "1024x1024",
		"response_format":     "b64_json",
		"seed":                float64(42),
		"strength":            0.5,
		"guidance_scale":      7.5,
		"num_inference_steps": float64(20),
	}
	for field, want := range checks {
		if bodyJSON[field] != want {
			t.Errorf("%s = %v, want %v", field, bodyJSON[field], want)
		}
	}

	files, err := filepath.Glob(filepath.Join(dir, "images", "*", "*.png"))
	if err != nil {
		t.Fatalf("Glob() error: %v", err)
	}
	if len(files) != 2 {
		t.Fatalf("files = %v, want two images", files)
	}

	for _, file := range files {
		data, err := os.ReadFile(file)
		if err != nil {
			t.Fatalf("ReadFile(%s) error: %v", file, err)
		}
		if string(data) != string(testutil.PNG) {
			t.Errorf("%s content = %q, want the generated bytes", file, data)
		}
	}

	if !strings.Contains(out, dir) || !strings.Contains(out, "Cost: $0.02") {
		t.Errorf("stdout does not contain the paths and cost:\n%s", out)
	}
}

