func TestGenerateImageResolvesInputAddresses(t *testing.T) {
	input := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		_, _ = w.Write(testutil.PNG)
	}))
	defer input.Close()

	encoded := base64.StdEncoding.EncodeToString(testutil.PNG)
	server, requests := testutil.CaptureServer(
		t,
		http.StatusOK,
		fmt.Sprintf(`{"data":[{"b64_json":%q}],"cost":0.01}`, encoded),
	)

	_, _, err := runNano(
		t,
		cli.Deps{Nano: testutil.NewNanoClient(t, server.URL)},
		"a cat",
		"--image",
		input.URL+"/image.png",
		"--images",
		input.URL+"/extra.png",
		"--mask",
		input.URL+"/mask.png",
		"--format",
		"png",
		"--out",
		t.TempDir(),
	)
	if err != nil {
		t.Fatalf("Execute() error: %v", err)
	}

	body := testutil.NextRequest(t, requests).JSONBody(t)
	wantDataURL := "data:image/png;base64," + encoded

	if body["imageDataUrl"] != wantDataURL {
		t.Errorf("imageDataUrl = %v, want the resolved input", body["imageDataUrl"])
	}
	if body["maskDataUrl"] != wantDataURL {
		t.Errorf("maskDataUrl = %v, want the resolved mask", body["maskDataUrl"])
	}

	images, ok := body["imageDataUrls"].([]any)
	if !ok || len(images) != 1 || images[0] != wantDataURL {
		t.Errorf("imageDataUrls = %v, want the resolved extra image", body["imageDataUrls"])
	}
}

func TestGenerateImageDownloadsAURLResult(t *testing.T) {
	var serverURL string
	server, requests := testutil.CaptureServerFunc(t, func(r *http.Request) (int, string) {
		switch r.URL.Path {
		case "/api/v1/images/generations":
			return http.StatusOK, fmt.Sprintf(
				`{"data":[{"url":%q}],"cost":0.03}`,
				serverURL+"/asset.png",
			)
		case "/asset.png":
			return http.StatusOK, string(testutil.PNG)
		default:
			return http.StatusNotFound, ""
		}
	})
	serverURL = server.URL

	dir := t.TempDir()

	if _, _, err := runNano(
		t,
		cli.Deps{Nano: testutil.NewNanoClient(t, server.URL)},
		"a cat",
		"--format",
		"png",
		"--out",
		dir,
	); err != nil {
		t.Fatalf("Execute() error: %v", err)
	}

	testutil.NextRequestPath(t, requests, "/api/v1/images/generations")

	files, err := filepath.Glob(filepath.Join(dir, "images", "*", "*.png"))
	if err != nil {
		t.Fatalf("Glob() error: %v", err)
	}
	if len(files) != 1 {
		t.Fatalf("files = %v, want one downloaded image", files)
	}

	data, err := os.ReadFile(files[0])
	if err != nil {
		t.Fatalf("ReadFile() error: %v", err)
	}
	if string(data) != string(testutil.PNG) {
		t.Errorf("downloaded content = %q, want the asset bytes", data)
	}
}

func TestGenerateImageLeavesNoFileWhenADownloadFails(t *testing.T) {
	var serverURL string
	server, _ := testutil.CaptureServerFunc(t, func(r *http.Request) (int, string) {
		switch r.URL.Path {
		case "/api/v1/images/generations":
			return http.StatusOK, fmt.Sprintf(
				`{"data":[{"url":%q}],"cost":0.03}`,
				serverURL+"/asset.png",
			)
		case "/asset.png":
			return http.StatusInternalServerError, "boom"
		default:
			return http.StatusNotFound, ""
		}
	})
	serverURL = server.URL

	dir := t.TempDir()

	_, _, err := runNano(
		t,
		cli.Deps{Nano: testutil.NewNanoClient(t, server.URL)},
		"a cat",
		"--out",
		dir,
	)
	if err == nil || !strings.Contains(err.Error(), "gen image") {
		t.Fatalf("Execute() error = %v, want a download failure", err)
	}

	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatalf("ReadDir() error: %v", err)
	}
	if len(entries) != 0 {
		t.Errorf("output directory contains %d files, want none", len(entries))
	}
}

